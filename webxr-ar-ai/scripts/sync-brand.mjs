#!/usr/bin/env node
/**
 * Copies the Companion Intelligence logo and icon files the app serves from the
 * pinned @companionintelligence/assets package into public/, and checks each
 * copy against the sha256 in that package's brand.config.json.
 *
 * The copies are generated, never hand-edited: they are gitignored and rebuilt
 * by predev / prebuild. Bump the package version in package.json, then run
 * `npm run build`. `npm run brand:check` verifies the copies without writing.
 *
 *   node scripts/sync-brand.mjs            copy and verify
 *   node scripts/sync-brand.mjs --check    verify only; exit 1 on any drift
 */

import { createHash } from 'node:crypto';
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PACKAGE_DIR = join(ROOT, 'node_modules/@companionintelligence/assets');
const PUBLIC_DIR = join(ROOT, 'public');
const CHECK_ONLY = process.argv.includes('--check');

/**
 * [path in the package, path under public/]. The tab icons sit at the site root,
 * where browsers look for them; the in-app lockups go under /brand/.
 */
const COPIES = [
  ['logos/mark-tight.svg', 'favicon.svg'],
  ['icons/png/favicon-16.png', 'favicon-16.png'],
  ['icons/png/favicon-32.png', 'favicon-32.png'],
  ['icons/png/favicon-48.png', 'favicon-48.png'],
  ['icons/png/favicon.ico', 'favicon.ico'],
  ['icons/png/apple-touch-icon-180.png', 'apple-touch-icon.png'],
  ['icons/png/icon-192.png', 'icon-192.png'],
  ['icons/png/icon-512.png', 'icon-512.png'],
  ['logos/mark.svg', 'brand/mark.svg'],
  ['logos/lockup.svg', 'brand/lockup-dark.svg'],
  ['logos/lockup-on-light.svg', 'brand/lockup-light.svg'],
];

function fail(message) {
  console.error(`sync-brand: ${message}`);
  process.exit(1);
}

if (!existsSync(join(PACKAGE_DIR, 'brand.config.json'))) {
  fail('@companionintelligence/assets is not installed; run `npm ci` first.');
}

const manifest = JSON.parse(readFileSync(join(PACKAGE_DIR, 'brand.config.json'), 'utf8'));

/** The manifest's declared sha256 for each available file, keyed by its path in the package. */
function declaredHashes(config) {
  const hashes = new Map();
  for (const section of ['logo', 'icons']) {
    for (const entry of Object.values(config[section] ?? {})) {
      if (entry?.path && entry.status === 'available' && entry.sha256) {
        hashes.set(entry.path, entry.sha256);
      }
    }
  }
  return hashes;
}

const sha256 = (buffer) => createHash('sha256').update(buffer).digest('hex');
const hashes = declaredHashes(manifest);
const problems = [];
const written = [];

for (const [source, target] of COPIES) {
  const sourcePath = join(PACKAGE_DIR, source);
  if (!existsSync(sourcePath)) {
    problems.push(`${source}: missing from the package`);
    continue;
  }
  const buffer = readFileSync(sourcePath);
  const actual = sha256(buffer);
  const declared = hashes.get(source);
  if (!declared) {
    problems.push(`${source}: not an available entry in brand.config.json`);
    continue;
  }
  if (actual !== declared) {
    problems.push(`${source}: sha256 ${actual} does not match the manifest ${declared}`);
    continue;
  }

  const targetPath = join(PUBLIC_DIR, target);
  if (CHECK_ONLY) {
    if (!existsSync(targetPath) || sha256(readFileSync(targetPath)) !== actual) {
      problems.push(`public/${target}: missing or out of date; run \`npm run build\``);
    }
    continue;
  }
  mkdirSync(dirname(targetPath), { recursive: true });
  copyFileSync(sourcePath, targetPath);
  written.push(`public/${target}`);
}

if (problems.length) fail(problems.join('\n  '));

if (!CHECK_ONLY) {
  // Record what was copied, and from which package version, next to the copies.
  const version = JSON.parse(readFileSync(join(PACKAGE_DIR, 'package.json'), 'utf8')).version;
  writeFileSync(
    join(PUBLIC_DIR, 'brand', 'SOURCE.txt'),
    `@companionintelligence/assets ${version}\nGenerated by scripts/sync-brand.mjs. Do not edit.\n`,
  );
  console.log(`sync-brand: ${written.length} files from @companionintelligence/assets ${version}`);
} else {
  console.log('sync-brand: public/ matches the pinned brand package');
}

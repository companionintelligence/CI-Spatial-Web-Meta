/**
 * ScanReport — renders a scan as a human-readable Markdown report.
 *
 * Exported alongside the GLB so every scan produces two artifacts:
 *   companion-scan-<ts>.glb  — geometry + machine-readable extras
 *   companion-scan-<ts>.md   — this report
 *
 * Pure string building (no DOM/three) so it is unit-testable and reusable by
 * both the headset app and the desktop viewer.
 */

/**
 * Build a Markdown report from serialised pins (the same shape as
 * `extras.companion_scan.pins` in the GLB — see GltfExporter).
 *
 * @param {object} scan companion_scan block: { session_id, exported_at, anchor_uuid, pins, floorplan }
 * @returns {string} markdown
 */
export function buildScanReport(scan) {
  const pins      = scan?.pins ?? [];
  const cvPins    = pins.filter(p => p.source === 'CvServer');
  const scenePins = pins.filter(p => p.source === 'MetaScene');
  const lines = [];

  lines.push('# Companion Scan Report');
  lines.push('');
  lines.push(`| | |`);
  lines.push(`|---|---|`);
  lines.push(`| Exported | ${scan?.exported_at ?? '—'} |`);
  lines.push(`| Session | \`${scan?.session_id ?? '—'}\` |`);
  lines.push(`| Anchor UUID | \`${scan?.anchor_uuid ?? '—'}\` |`);
  lines.push(`| Pins | ${pins.length} (${cvPins.length} detections · ${scenePins.length} scene surfaces) |`);

  const b = scan?.floorplan?.bounds;
  if (b?.min && b?.max) {
    const dims = [b.max.x - b.min.x, b.max.y - b.min.y, b.max.z - b.min.z]
      .map(v => v.toFixed(1)).join(' × ');
    lines.push(`| Room bounds | ${dims} m |`);
  }
  lines.push('');

  // ── Scene surfaces (Pipeline A) ───────────────────────────────────────────
  if (scenePins.length) {
    lines.push('## Room structure (WebXR Scene Understanding)');
    lines.push('');
    lines.push('| Surface | Type | Position (anchor-local) | Size |');
    lines.push('|---|---|---|---|');
    for (const p of scenePins) {
      lines.push(`| ${p.label ?? '—'} | ${p.hit_type ?? '—'} | ${_pos(p)} | ${_extents(p)} |`);
    }
    lines.push('');
  }

  // ── Detections (Pipeline B) ───────────────────────────────────────────────
  if (cvPins.length) {
    lines.push('## Detected objects (CV pipeline)');
    lines.push('');
    lines.push('| Object | Confidence | Placement | Position (anchor-local) |');
    lines.push('|---|---|---|---|');
    for (const p of cvPins) {
      const conf = `${Math.round((p.confidence ?? 0) * 100)}%`;
      lines.push(`| ${p.label ?? '—'} | ${conf} | ${_placement(p)} | ${_pos(p)} |`);
    }
    lines.push('');

    const captions = [...new Set(cvPins.map(p => p.florence_caption).filter(Boolean))];
    if (captions.length) {
      lines.push('### Scene descriptions (Florence-2)');
      lines.push('');
      for (const c of captions) lines.push(`> ${c}`);
      lines.push('');
    }
  }

  if (!pins.length) {
    lines.push('_No pins captured._');
    lines.push('');
  }

  lines.push('---');
  lines.push('_Generated by Companion Scan. Pair this report with the matching `.glb` — open it in the desktop viewer (`/viewer.html`) to explore the scan in 3D._');
  lines.push('');
  return lines.join('\n');
}

// ── Helpers ────────────────────────────────────────────────────────────────

function _pos(pin) {
  const p = pin.position_anchor_local ?? pin.position;
  if (!p) return '—';
  return `(${p.x.toFixed(2)}, ${p.y.toFixed(2)}, ${p.z.toFixed(2)})`;
}

function _extents(pin) {
  const e = pin.plane_extents ?? pin.volume_extents;
  if (!e?.size) return '—';
  const parts = [e.size.x, e.size.y, e.size.z]
    .filter(v => v > 0.001)
    .map(v => v.toFixed(2));
  return parts.length ? `${parts.join(' × ')} m` : '—';
}

function _placement(pin) {
  switch (pin.hit_type) {
    case 'mesh':     return 'on room mesh';
    case 'plane':    return 'on plane';
    case 'fallback': return `estimated (${Math.round((pin.placement_confidence ?? 0) * 100)}%)`;
    default:         return pin.hit_type ?? '—';
  }
}
